import { handoffInputs } from './snapshots.mjs';
import { read } from './io.mjs';
import { md } from './documents.mjs';
export function handoffDocument(base, approvals) {
  const inputs = handoffInputs(base);
  const notes = read(base, '08-handoff/implementation-notes.md').toString('utf8');
  const open = read(base, '08-handoff/open-items.md').toString('utf8');
  const links = Object.keys(inputs).map(path => `- [${md(path)}](../${encodeURI(path).replace(/[()]/g, c => encodeURIComponent(c))})`).join('\n');
  const approvalRows = Object.entries(approvals).map(([stage, value]) => `| ${md(stage)} | ${md(value)} |`).join('\n');
  return { inputs, content: `<!-- Generated by design-harness handoff. -->\n# HANDOFF\n\n## Approved design versions\n\n| Stage | Approval ID |\n| --- | --- |\n${approvalRows}\n\n## Implementation notes\n\n${notes}\n\n## Open items\n\n${open}\n\n## Source artifacts\n\n${links}\n\n## Delivery scope\n\nThis package records checked artifact versions and human approvals. It does not implement or deploy product code. Confirm native behavior, remaining issues and Figma-specific checks before release.\n` };
}
